from ..framework.models import (
    AgentMessage,
    AgentRole,
    DeliberationSession,
    MessageType,
    SeverityLevel,
)


@dataclass
class HorizonState:
    """Projected station state at a specific future horizon."""
    horizon_seconds: float
    horizon_label: str
    indoor_temp_c: float
    fuel_level_l: float
    fuel_autonomy_days: float
    battery_soc_pct: float
    composite_risk: float
    violations: list[str] = field(default_factory=list)


@dataclass
class PredictionProjection:
    """Comprehensive multi-horizon predictive outcome generated by PredictionAgent."""
    prediction_id: str
    session_id: str
    timestamp: float
    current_trend: str
    time_to_critical_seconds: float | None
    critical_breach_type: str | None
    horizons: dict[str, dict[str, Any]]
    trajectory: dict[str, list[float]]
    violations_detected: list[str]
    confidence: float
    summary: str

    def to_dict(self) -> dict[str, Any]:
        """Serialize projection outcome to dictionary."""
        return asdict(self)


class PredictionAgent(BaseSpecializedAgent):
    """Specialized cognitive agent responsible for forward projection and Time-to-Failure forecasting."""

    def __init__(
        self,
        bus: AgentMessageBus,
        engine: BharatiMasterTwinEngine,
        graph: TwinCausalGraph,
    ) -> None:
        super().__init__(
            role=AgentRole.PREDICTION,
            bus=bus,
            engine=engine,
            graph=graph,
        )

        # Listen for DIAGNOSIS messages to trigger lookahead forecasting
        self.bus.subscribe_type(MessageType.DIAGNOSIS, self.on_diagnosis_received)

        # Audit cache of generated predictions: prediction_id -> PredictionProjection
        self._predictions: dict[str, PredictionProjection] = {}

    def on_diagnosis_received(self, message: AgentMessage) -> None:
        """Automatic deliberation hook triggered when DiagnosticAgent publishes a DIAGNOSIS."""
        session_id = message.session_id

        # Run 4-hour forward lookahead from current engine state
        projection = self.project_forward(
            duration_hours=4.0,
            session_id=session_id,
            dt_seconds=60.0,
        )

        # Record in local audit cache
        self._predictions[projection.prediction_id] = projection

        # Update DeliberationSession blackboard if session exists
        if session_id:
            session = self.bus.get_session(session_id)
            if session:
                session.predictions.append(projection.to_dict())

        # Determine urgency based on time to critical breach
        severity = (
            SeverityLevel.EMERGENCY
            if (projection.time_to_critical_seconds is not None and projection.time_to_critical_seconds < 1800)
            else (
                SeverityLevel.CRITICAL
                if projection.time_to_critical_seconds is not None
                else SeverityLevel.WARNING
            )
        )

        proj_payload = projection.to_dict()

        # Publish PREDICTION_PROJECTION to Risk & Impact Agent
        self.publish_message(
            session_id=session_id,
            recipient=AgentRole.RISK_IMPACT,
            message_type=MessageType.PREDICTION_PROJECTION,
            severity=severity,
            payload=proj_payload,
            confidence=projection.confidence,
        )

        # Publish PREDICTION_PROJECTION to Planning Agent
        self.publish_message(
            session_id=session_id,
            recipient=AgentRole.PLANNING,
            message_type=MessageType.PREDICTION_PROJECTION,
            severity=severity,
            payload=proj_payload,
            confidence=projection.confidence,
        )

    def handle_message(self, message: AgentMessage) -> None:
        """Handle direct queries or status requests addressed to PREDICTION role."""
        if message.message_type == MessageType.QUERY:
            duration = float(message.payload.get("duration_hours", 4.0))
            metric = message.payload.get("metric")

            if metric:
                # Targeted Time-to-Failure lookup
                ttf_result = self.calculate_time_to_failure(metric)
                self.publish_message(
                    session_id=message.session_id,
                    recipient=message.sender,
                    message_type=MessageType.RESPONSE,
                    severity=SeverityLevel.INFO,
                    payload=ttf_result,
                    confidence=1.0,
                )
            else:
                # Full forward lookahead projection
                projection = self.project_forward(
                    duration_hours=duration,
                    session_id=message.session_id,
                )
                self.publish_message(
                    session_id=message.session_id,
                    recipient=message.sender,
                    message_type=MessageType.RESPONSE,
                    severity=SeverityLevel.INFO,
                    payload=projection.to_dict(),
                    confidence=projection.confidence,
                )

    def project_forward(
        self,
        duration_hours: float = 4.0,
        session_id: str = "",
        dt_seconds: float = 60.0,
    ) -> PredictionProjection:
        """Fork isolated TwinSandbox and simulate unmitigated trajectory forward in time."""
        duration_seconds = duration_hours * 3600.0

        # Fork sandbox cleanly from current master twin state
        sandbox = self.fork_sandbox()

        # Run accelerated forward simulation
        traj: TrajectoryResult = sandbox.run_fast_forward(
            duration_seconds=duration_seconds,
            dt_seconds=dt_seconds,
        )

        # Evaluate horizons at 15m (900s), 1h (3600s), 4h (14400s)
        step_dt = dt_seconds
        idx_15m = min(int(900.0 / step_dt) - 1, len(traj.time_points_hours) - 1)
        idx_1h = min(int(3600.0 / step_dt) - 1, len(traj.time_points_hours) - 1)
        idx_4h = len(traj.time_points_hours) - 1

        horizons: dict[str, dict[str, Any]] = {}

        for label, idx in [("15m", idx_15m), ("1h", idx_1h), ("4h", idx_4h)]:
            if idx >= 0 and idx < len(traj.time_points_hours):
                horizons[label] = {
                    "time_hours": traj.time_points_hours[idx],
                    "indoor_temp_c": traj.indoor_temp_c[idx],
                    "fuel_reserve_l": traj.fuel_level_l[idx],
                    "station_load_kw": traj.station_load_kw[idx],
                    "battery_soc_pct": traj.battery_soc_pct[idx],
                    "risk_score": traj.risk_score[idx],
                }

        # Calculate exact Time-to-Failure (TtF) for life-support violations
        time_to_crit: float | None = None
        breach_type: str | None = None

        # 1. Check thermal violation (< 16.0°C)
        for i, temp in enumerate(traj.indoor_temp_c):
            if temp < 16.0:
                sec = (i + 1) * step_dt
                if time_to_crit is None or sec < time_to_crit:
                    time_to_crit = sec
                    breach_type = "THERMAL_LIFE_SUPPORT_BREACH"
                break

        # 2. Check battery depletion (< 20.0%)
        for i, soc in enumerate(traj.battery_soc_pct):
            if soc < 20.0:
                sec = (i + 1) * step_dt
                if time_to_crit is None or sec < time_to_crit:
                    time_to_crit = sec
                    breach_type = "BATTERY_RESERVE_DEPLETION"
                break

        # 3. Check pipe freeze (if pipe temp was recorded below 0.0°C)
        cur_pipe_temp = self._extract_sensor("BHARATI-PIPE-WATER01-TEMP", default=4.0)
        if cur_pipe_temp <= 1.0:
            ttf_pipe = self._estimate_pipe_freeze_seconds(cur_pipe_temp)
            if time_to_crit is None or ttf_pipe < time_to_crit:
                time_to_crit = ttf_pipe
                breach_type = "UTILIDOR_WATER_LINE_FREEZE"

        # 4. Check fuel day tank depletion
        cur_fuel_pct = self._extract_sensor("BHARATI.FUEL.DAYTANK.PERCENT", default=85.0)
        cur_fuel_lvl = self._extract_sensor("BHARATI.FUEL.DAYTANK.LEVEL", default=850.0)
        fuel_flow = self._extract_sensor("BHARATI.FUEL.FLOW", default=0.0)
        if cur_fuel_pct < 20.0 and fuel_flow <= 0.1:
            ttf_fuel = (cur_fuel_lvl / max(18.0, 1.0)) * 3600.0  # seconds until dry
            if time_to_crit is None or ttf_fuel < time_to_crit:
                time_to_crit = round(ttf_fuel, 1)
                breach_type = "DAY_TANK_FUEL_EXHAUSTION"

        pred_id = f"PRED-{int(time.time() * 1000) % 1000000:06d}"

        # Formulate human-readable summary
        summary = self._formulate_summary(time_to_crit, breach_type, horizons)

        # Classify current trend
        trend = "CRITICAL_DEGRADATION" if time_to_crit is not None else (
            "MODERATE_DRIFT" if traj.violations else "STABLE"
        )

        confidence = 0.92 if time_to_crit is not None else 0.95

        return PredictionProjection(
            prediction_id=pred_id,
            session_id=session_id or f"SES-{pred_id}",
            timestamp=time.time(),
            current_trend=trend,
            time_to_critical_seconds=time_to_crit,
            critical_breach_type=breach_type,
            horizons=horizons,
            trajectory={
                "time_hours": traj.time_points_hours,
                "indoor_temp_c": traj.indoor_temp_c,
                "fuel_level_l": traj.fuel_level_l,
                "risk_score": traj.risk_score,
                "battery_soc_pct": traj.battery_soc_pct,
            },
            violations_detected=traj.violations,
            confidence=confidence,
            summary=summary,
        )

    def calculate_time_to_failure(self, metric: str) -> dict[str, Any]:
        """Compute targeted Time-to-Failure (TtF) for a specific physical parameter."""
        metric_norm = metric.lower()

        if "temp" in metric_norm or "thermal" in metric_norm:
            cur_temp = self._extract_sensor("BHARATI-BLDG-Z01-TEMP", default=21.0)
            amb_temp = self._extract_sensor("ENV-WX-TEMP", default=-15.0)
            threshold = 16.0  # Life-support minimum

            if cur_temp <= threshold:
                return {
                    "metric": "INDOOR_TEMPERATURE",
                    "time_to_failure_seconds": 0.0,
                    "status": "IMMEDIATE_BREACH",
                    "current_value": cur_temp,
                    "threshold": threshold,
                }

            # Thermal decay time constant tau ≈ 3.0 hours (10,800 seconds)
            tau_seconds = 10800.0
            if cur_temp > amb_temp and threshold > amb_temp:
                # T(t) = T_amb + (T_0 - T_amb) * e^(-t / tau)
                ratio = (threshold - amb_temp) / (cur_temp - amb_temp)
                if 0 < ratio < 1.0:
                    ttf = -tau_seconds * math.log(ratio)
                    return {
                        "metric": "INDOOR_TEMPERATURE",
                        "time_to_failure_seconds": round(ttf, 1),
                        "time_to_failure_minutes": round(ttf / 60.0, 1),
                        "status": "PROJECTED_BREACH",
                        "current_value": cur_temp,
                        "threshold": threshold,
                    }

            return {
                "metric": "INDOOR_TEMPERATURE",
                "time_to_failure_seconds": None,
                "status": "NO_PROJECTED_BREACH",
                "current_value": cur_temp,
                "threshold": threshold,
            }

        elif "fuel" in metric_norm:
            day_lvl = self._extract_sensor("BHARATI.FUEL.DAYTANK.LEVEL", default=850.0)
            fuel_burn = 24.0  # liters per hour under typical 65 kW load
            ttf_hours = day_lvl / fuel_burn
            ttf_seconds = ttf_hours * 3600.0

            return {
                "metric": "DAY_TANK_FUEL",
                "time_to_failure_seconds": round(ttf_seconds, 1),
                "time_to_failure_hours": round(ttf_hours, 2),
                "status": "DEPLETION_TRACKED",
                "current_value_liters": day_lvl,
                "threshold_liters": 50.0,
            }

        elif "pipe" in metric_norm or "water" in metric_norm:
            pipe_t = self._extract_sensor("BHARATI-PIPE-WATER01-TEMP", default=4.0)
            ttf = self._estimate_pipe_freeze_seconds(pipe_t)
            return {
                "metric": "UTILIDOR_WATER_PIPE",
                "time_to_failure_seconds": round(ttf, 1),
                "time_to_failure_minutes": round(ttf / 60.0, 1),
                "status": "FREEZE_TRACKED" if ttf < 7200.0 else "NOMINAL",
                "current_value_c": pipe_t,
                "threshold_c": 0.0,
            }

        return {
            "metric": metric,
            "error": f"Unknown metric '{metric}'. Supported: temp, fuel, pipe/water.",
        }

    def _estimate_pipe_freeze_seconds(self, current_pipe_temp: float) -> float:
        """Estimate seconds until utilidor water freezes without heating."""
        if current_pipe_temp <= 0.0:
            return 0.0
        amb_t = self._extract_sensor("ENV-WX-TEMP", default=-25.0)
        # Pipe thermal decay constant tau ≈ 20 minutes (1200 seconds)
        tau = 1200.0
        if current_pipe_temp > amb_t and 0.0 > amb_t:
            ratio = (0.0 - amb_t) / (current_pipe_temp - amb_t)
            if 0 < ratio < 1.0:
                return -tau * math.log(ratio)
        return 1800.0  # Default 30 min fallback

    def _extract_sensor(self, sensor_id: str, default: float = 0.0) -> float:
        """Lookup sensor reading safely handling SensorReading objects."""
        try:
            val = self.engine.get_sensor_reading(sensor_id)
            if hasattr(val, "value"):
                return float(val.value)
            return float(val)
        except Exception:
            return default

    def _formulate_summary(
        self,
        time_to_crit: float | None,
        breach_type: str | None,
        horizons: dict[str, dict[str, Any]],
    ) -> str:
        """Create a clear operational forecasting narrative."""
        if time_to_crit is not None:
            mins = round(time_to_crit / 60.0, 1)
            return (
                f"CRITICAL BREACH IMMINENT: '{breach_type}' projected in {mins} minutes ({time_to_crit:.0f}s) "
                f"under unmitigated station conditions. At 1h horizon, indoor temp drops to "
                f"{horizons.get('1h', {}).get('indoor_temp_c', 0.0):.1f}°C."
            )
        else:
            t4 = horizons.get("4h", {}).get("indoor_temp_c", 20.0)
            return (
                f"STABLE FORWARD TRAJECTORY: No life-support or critical threshold violations projected "
                f"over the next 4 hours. Projected indoor temp at +4h: {t4:.1f}°C."
            )
