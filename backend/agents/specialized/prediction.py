"""Prediction Agent for F.R.I.D.A.Y. Platform.

Part of SIH 2026 Project SIH26060: F.R.I.D.A.Y.
Digital Platform for Efficient Remote Management of Indian Antarctic Research Stations.
Target: Bharati Research Station, Larsemann Hills, East Antarctica.

COGNITIVE OBJECTIVE:
"What is likely to happen next across station operations if unmitigated?"

RESPONSIBILITIES:
1. Fast Forward-Lookahead Forecasting: Spawns isolated in-memory TwinSandbox simulations
   to project station dynamics across 15-minute, 1-hour, and 4-hour operational horizons.
2. Time-to-Failure (TtF) & Time-to-Violation (TtV) Estimation:
   - Computes exact seconds until life-support guardrails are breached (e.g. indoor temp < 16.0°C).
   - Computes time until day tank diesel exhaustion (fuel < 50 L).
   - Computes time until utilidor fresh water line freezing (pipe temp <= 0.0°C).
   - Computes battery backup exhaustion (UPS SOC < 20%).
3. Multi-Horizon State Forecasting: Projects fuel reserves, indoor temperatures, electrical load,
   and composite risk scores at discrete milestones (15m, 1h, 4h).
4. Multi-Agent Deliberation Integration:
   - Listens to DIAGNOSIS and ALERT messages on the Agent Message Bus.
   - Automatically updates DeliberationSession blackboards with forward projection data.
   - Dispatches PREDICTION_PROJECTION messages to Risk & Impact and Planning agents.
5. Interactive Lookahead Queries: Responds to operator inquiries with time-series trajectories
   and breach warnings.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
import math
import time
from typing import Any, Literal

from ...core.causal_graph import TwinCausalGraph
from ...core.engine import BharatiMasterTwinEngine, MasterScenario
from ...core.sandbox import TrajectoryResult, TwinSandbox
from ..framework.base_agent import BaseSpecializedAgent
