# ==============================================================================
# Helper to generate deterministic confidence from evidence level
# ==============================================================================
def get_confidence_for_evidence(evidence: EvidenceLevel) -> float:
    """Return deterministic confidence based on evidentiary grounding."""
    if evidence == EvidenceLevel.DOCUMENTED:
        return 1.0
    elif evidence == EvidenceLevel.IMPLIED:
        return 0.90
    elif evidence == EvidenceLevel.DERIVED:
        return 0.85
    else:  # NOT_PUBLICLY_CONFIRMED
        return 0.75


