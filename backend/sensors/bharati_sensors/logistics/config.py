# Standard confidence mappings aligned with Energy, Infrastructure, and Environment
CONFIDENCE_BY_EVIDENCE: dict[EvidenceLevel, float] = {
    EvidenceLevel.DOCUMENTED: 1.0,
    EvidenceLevel.IMPLIED: 0.8,
    EvidenceLevel.DERIVED: 0.85,
    EvidenceLevel.NOT_PUBLICLY_CONFIRMED: 0.65,
}


def get_confidence_for_evidence(evidence_level: EvidenceLevel) -> float:
    """Return confidence score corresponding to the evidence level."""
    return CONFIDENCE_BY_EVIDENCE.get(evidence_level, 0.7)


