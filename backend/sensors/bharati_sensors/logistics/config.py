# Lookup dictionaries for fast access
CONFIG_BY_ID: dict[str, SensorConfig] = {cfg.sensor_id: cfg for cfg in BHARATI_LOGISTICS_SENSORS}
CONFIGS_BY_DOMAIN: dict[LogisticsDomain, list[SensorConfig]] = {}
for cfg in BHARATI_LOGISTICS_SENSORS:
    CONFIGS_BY_DOMAIN.setdefault(cfg.domain, []).append(cfg)


def validate_catalogue() -> None:
    """Validate catalogue invariants: count, uniqueness, units, schemas."""
    total_count = len(BHARATI_LOGISTICS_SENSORS)
    if total_count != 98:
        raise ValueError(f"Expected exactly 98 sensors in catalogue, found {total_count}")

    seen_ids = set()
    for cfg in BHARATI_LOGISTICS_SENSORS:
        if cfg.sensor_id in seen_ids:
            raise ValueError(f"Duplicate sensor_id found: {cfg.sensor_id}")
        seen_ids.add(cfg.sensor_id)

        # Enforce derived typing rule
        if cfg.domain == LogisticsDomain.DERIVED and cfg.sensor_id != "LOG-DERIVED-LOGISTICS-CONDITION":
            if cfg.kind != SensorKind.DERIVED:
                raise ValueError(
                    f"Derived domain sensor {cfg.sensor_id} must have kind SensorKind.DERIVED, got {cfg.kind}"
                )

        # Enforce state vs instrument typing
        if cfg.kind == SensorKind.INSTRUMENT and cfg.physical_quantity == PhysicalQuantity.STATUS:
            raise ValueError(f"Status sensor {cfg.sensor_id} cannot have kind INSTRUMENT")

    # Domain count assertions
    domain_counts = {dom: len(configs) for dom, configs in CONFIGS_BY_DOMAIN.items()}
    expected_domain_counts = {
        LogisticsDomain.FLEET: 16,
        LogisticsDomain.CARGO: 10,
        LogisticsDomain.FUEL: 10,
        LogisticsDomain.COLD_CHAIN: 8,
        LogisticsDomain.AVIATION: 7,
        LogisticsDomain.MARINE: 7,
        LogisticsDomain.ROUTES: 8,
        LogisticsDomain.MISSIONS: 9,
        LogisticsDomain.INVENTORY: 10,
        LogisticsDomain.WASTE: 5,
        LogisticsDomain.DERIVED: 8,
    }
    for dom, expected in expected_domain_counts.items():
        actual = domain_counts.get(dom, 0)
        if actual != expected:
            raise ValueError(f"Domain {dom} expected {expected} points, got {actual}")


# Validate on import
validate_catalogue()
